"""Pin the installed dependency closure; this does not resolve another platform."""

import subprocess
import sys
import sysconfig
import tomllib
from collections import deque
from importlib.metadata import distribution
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parents[1]


def main() -> None:
    if Path(sys.prefix).name != "postgres-query-optimizer":
        raise SystemExit("Run inside the selected postgres-query-optimizer environment")
    subprocess.run([sys.executable, "-m", "pip", "check"], check=True)
    project = tomllib.loads((ROOT / "pyproject.toml").read_text())
    for dev, filename in ((False, "requirements.lock"), (True, "requirements-dev.lock")):
        roots = project["project"]["dependencies"] + project["build-system"]["requires"] + ["wheel"]
        if dev:
            roots += project["project"]["optional-dependencies"]["dev"]
        queue = deque(Requirement(raw) for raw in roots)
        versions: dict[str, str] = {}
        extras: dict[str, set[str]] = {}
        while queue:
            requirement = queue.popleft()
            name = canonicalize_name(requirement.name)
            installed = distribution(name)
            if not requirement.specifier.contains(installed.version, prereleases=True):
                raise SystemExit(f"Installed {name}=={installed.version} violates {requirement}")
            selected = set(requirement.extras) | extras.get(name, set())
            if name in versions and selected == extras[name]:
                continue
            versions[name], extras[name] = installed.version, selected
            for raw in installed.requires or []:
                child = Requirement(raw)
                if child.marker is None or any(
                    child.marker.evaluate({"extra": extra}) for extra in selected | {""}
                ):
                    queue.append(child)
        header = (
            f"# Installed dependency snapshot: Python {sys.version.split()[0]}, "
            f"{sysconfig.get_platform()}.\n"
            "# Generated by scripts/lock_dependencies.py after pip check passed.\n"
            "# Includes build dependencies; excludes the editable project.\n"
            "# Clean installation and Linux compatibility remain unverified.\n"
        )
        (ROOT / filename).write_text(
            header + "".join(f"{name}=={versions[name]}\n" for name in sorted(versions))
        )
        print(f"{filename}: {len(versions)} pinned distributions")


if __name__ == "__main__":
    main()
