CREATE ROLE pgo_app LOGIN PASSWORD 'local_app_only' NOSUPERUSER NOCREATEDB NOCREATEROLE;
CREATE DATABASE pgo_app OWNER pgo_app;
\connect pgo_app
REVOKE ALL ON DATABASE pgo_app FROM PUBLIC;
GRANT CONNECT ON DATABASE pgo_app TO pgo_app;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
GRANT USAGE, CREATE ON SCHEMA public TO pgo_app;
